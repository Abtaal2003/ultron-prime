// Regenerates the frontend's API and event types from the backend's exported schemas.
// CI runs this and fails on any diff (spec 6.4, contract safety).
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import { compile } from "json-schema-to-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = resolve(root, "src/lib/schemas");
const python = process.env.ULTRON_PYTHON ?? resolve(root, "../.venv/bin/python");

execFileSync(python, ["-m", "src.cli", "export-schemas", "--out", out], {
  cwd: resolve(root, ".."),
  stdio: "inherit",
});

const header = "/* eslint-disable */\n// GENERATED by scripts/gen-types.mjs from the backend schemas. Do not edit.\n";

const api = await openapiTS(JSON.parse(readFileSync(resolve(out, "openapi.json"), "utf8")));
writeFileSync(resolve(root, "src/lib/api.gen.ts"), header + astToString(api));

const events = JSON.parse(readFileSync(resolve(out, "events.schema.json"), "utf8"));
const ts = await compile(events, "AgentEvent", {
  bannerComment: "",
  additionalProperties: false,
  unreachableDefinitions: true,
  format: true,
});
writeFileSync(resolve(root, "src/lib/events.gen.ts"), header + ts);
console.log("generated api.gen.ts and events.gen.ts");
